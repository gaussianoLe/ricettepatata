import {readFileSync} from 'node:fs';
import {currentValidationState} from '../src/catalog/validation-cycle.mjs';
import {parseArgs} from 'node:util';
import {readCatalog} from '../src/catalog/io.mjs';
import {integrationInputs,validateIntegration} from '../src/catalog/integration.mjs';
const {values}=parseArgs({options:{write:{type:'boolean',default:false}}});
if(values.write)throw new Error('Baseline P1.5 storica: --write non consentito');
const current=readCatalog(),registry=JSON.parse(readFileSync('src/catalog/registry.json','utf8'));
const history=currentValidationState(current,registry);
const report=validateIntegration(integrationInputs(),history.historicalEntries,registry,history.readHistorical);
const file='docs/integration/p1.5/report.json',text=JSON.stringify(report,null,2)+'\n';
if(readFileSync(file,'utf8')!==text)throw new Error('Report P1.5 obsoleto');
console.log(JSON.stringify(report.summary));
